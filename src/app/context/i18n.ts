export function useTranslation() {
  const { settings } = useController();
  const lang = settings.language;
  const dict = TRANSLATIONS[lang] || EN;

  const t = useCallback(
    (key: TranslationKey): string => dict[key] ?? EN[key] ?? key,
    [dict],
  );

  return { t, lang };
}

/** Standalone accessor (for outside React) */
export function getTranslation(lang: Language, key: TranslationKey): string {
  const dict = TRANSLATIONS[lang] || EN;
  return dict[key] ?? EN[key] ?? key;
}

/* ━━━ Pluralization System ━━━ */

/**
 * Plural rules per language family.
 *
 * Usage:
 *   const plural = usePlural();
 *   plural(count, { one: '1 entry', other: '{n} entries' })
 *   // Russian with complex forms:
 *   plural(count, { one: '{n} запись', few: '{n} записи', many: '{n} записей', other: '{n} записей' })
 */
export type PluralForms = {
  zero?: string;
  one: string;
  two?: string;
  few?: string;
  many?: string;
  other: string;
};

type PluralCategory = 'zero' | 'one' | 'two' | 'few' | 'many' | 'other';

function getPluralCategory(n: number, lang: Language): PluralCategory {
  if (n === 0 && lang !== 'ar') return 'other';

  switch (lang) {
    case 'ar': {
      if (n === 0) return 'zero';
      if (n === 1) return 'one';
      if (n === 2) return 'two';
      const mod100 = n % 100;
      if (mod100 >= 3 && mod100 <= 10) return 'few';
      if (mod100 >= 11 && mod100 <= 99) return 'many';
      return 'other';
    }
    case 'ru': {
      const mod10 = n % 10;
      const mod100 = n % 100;
      if (mod10 === 1 && mod100 !== 11) return 'one';
      if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'few';
      return 'many';
    }
    default: {
      return n === 1 ? 'one' : 'other';
    }
  }
}

function resolvePlural(n: number, forms: PluralForms, lang: Language): string {
  const cat = getPluralCategory(n, lang);
  const template = forms[cat] ?? forms.other;
  return template.replace(/\{n\}/g, String(n));
}

/** Hook-based plural helper */
export function usePlural() {
  const { lang } = useTranslation();
  return useCallback(
    (n: number, forms: PluralForms): string => resolvePlural(n, forms, lang),
    [lang]
  );
}
